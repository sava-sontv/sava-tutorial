/**
 * Chạy ensure-category-json, apply-articles-json, generate-sidebar, sync-docs-i18n rồi start Docusaurus.
 * Watcher chạy TRONG CÙNG PROCESS: khi sửa _category.json hoặc _articles.json thì tự chạy lại script → giao diện cập nhật.
 * apply-articles-json chỉ chạy lúc đầu để đảm bảo _articles.json được tạo/cập nhật.
 * Sidebar được generate trực tiếp từ _articles.json (không cần ghi frontmatter).
 */
const fs = require('fs');
const path = require('path');
const { spawnSync, spawn } = require('child_process');

const ROOT = path.join(__dirname, '..');
const DOCS = path.join(ROOT, 'docs');
const SIDEBARS_PATH = path.join(ROOT, 'sidebars.autogenerated.js');
const CONFIG_PATH = path.join(ROOT, 'docusaurus.config.ts');
const CATEGORY_META = '_category.json';
const ARTICLES_FILE = '_articles.json';
const DOCS_GLOB_MD = '**/*.md';
const DOCS_GLOB_MDX = '**/*.mdx';

function runSync(name) {
  const r = spawnSync('node', [path.join(__dirname, name)], {
    cwd: ROOT,
    stdio: 'inherit',
    shell: true,
  });
  return r.status === 0;
}

/** Touch sidebars + config để Docusaurus dev server reload và đọc lại sidebar (sort/active). */
function touchSidebars() {
  const now = Date.now() / 1000;
  try {
    if (fs.existsSync(SIDEBARS_PATH)) {
      let content = fs.readFileSync(SIDEBARS_PATH, 'utf8');
      content = content.replace(/\n?\s*\/\/ touched \d+\s*$/, '');
      content = content.trimEnd() + `\n// touched ${Date.now()}\n`;
      fs.writeFileSync(SIDEBARS_PATH, content, 'utf8');
    }
    if (fs.existsSync(CONFIG_PATH)) {
      fs.utimesSync(CONFIG_PATH, now, now);
    }
  } catch (_) {}
}

// Bước đầu: luôn sinh lại sidebar từ _category.json và _articles.json (sort, active)
console.log('[start-with-watch] Đang chạy ensure-category-json, apply-articles-json, generate-sidebar, sync-docs-i18n...');
runSync('ensure-category-json.js');
runSync('apply-articles-json.js');
runSync('generate-sidebar.js');
runSync('sync-docs-i18n.js');
console.log('[start-with-watch] Xong. Khởi động Docusaurus.');

let pendingCategory = false;
let pendingArticles = false;
let pendingDocs = false;
let debounceTimer = null;
const DEBOUNCE_MS = 500;

function onFileChange(filePath) {
  const name = path.basename(filePath);
  if (name === CATEGORY_META) {
    pendingCategory = true;
  } else if (name === ARTICLES_FILE) {
    pendingArticles = true;
  } else if (
    (name.endsWith('.md') || name.endsWith('.mdx')) &&
    !name.startsWith('_')
  ) {
    pendingDocs = true;
  }
  if (debounceTimer) clearTimeout(debounceTimer);
  debounceTimer = setTimeout(() => {
    debounceTimer = null;
    if (pendingCategory) {
      pendingCategory = false;
      console.log('\n[watch] _category.json thay đổi → chạy ensure-category-json + generate-sidebar + sync-docs-i18n');
      runSync('ensure-category-json.js');
      runSync('generate-sidebar.js');
      runSync('sync-docs-i18n.js');
      touchSidebars();
    }
    if (pendingArticles) {
      pendingArticles = false;
      console.log('\n[watch] _articles.json thay đổi → chạy generate-sidebar + sync-docs-i18n');
      // Không cần chạy apply-articles-json vì nó chỉ tự động thêm bài mới vào JSON
      // Khi user sửa _articles.json (active/sort), chỉ cần regenerate sidebar
      runSync('generate-sidebar.js');
      runSync('sync-docs-i18n.js');
      touchSidebars();
    }
    if (pendingDocs) {
      pendingDocs = false;
      console.log('\n[watch] docs/*.md thay đổi → chạy sync-docs-i18n');
      runSync('sync-docs-i18n.js');
    }
  }, DEBOUNCE_MS);
}

function startWatcher() {
  if (!fs.existsSync(DOCS)) return null;

  const globCategory = path.join(DOCS, '**', CATEGORY_META).replace(/\\/g, '/');
  const globArticles = path.join(DOCS, '**', ARTICLES_FILE).replace(/\\/g, '/');
  const globDocsMd = path.join(DOCS, DOCS_GLOB_MD).replace(/\\/g, '/');
  const globDocsMdx = path.join(DOCS, DOCS_GLOB_MDX).replace(/\\/g, '/');

  try {
    const chokidar = require('chokidar');
    const watcher = chokidar.watch(
      [globCategory, globArticles, globDocsMd, globDocsMdx],
      {
      persistent: true,
      ignoreInitial: true,
      awaitWriteFinish: { stabilityThreshold: 200 },
      }
    );
    watcher.on('change', (p) => onFileChange(p));
    watcher.on('add', (p) => onFileChange(p));
    watcher.on('ready', () => {
      console.log('[watch] Đang theo dõi _category.json và _articles.json trong docs/');
    });
    watcher.on('error', (err) => console.error('[watch] Lỗi:', err.message));
    return watcher;
  } catch (_) {
    console.log('[watch] Chưa cài chokidar. Chạy: yarn add -D chokidar');
    try {
      fs.watch(DOCS, { recursive: true }, (event, filename) => {
        if (filename && (filename.includes(CATEGORY_META) || filename.includes(ARTICLES_FILE))) {
          onFileChange(path.join(DOCS, filename));
        }
      });
      console.log('[watch] Đang theo dõi (fs.watch) _category.json và _articles.json');
      return { close: () => {} };
    } catch (e) {
      console.error('[watch] Lỗi fs.watch:', e.message);
      return null;
    }
  }
}

const watcher = startWatcher();

const docusaurusArgs = ['docusaurus', 'start', '--host', 'savrse.savameta.local', '--port', '3000', ...process.argv.slice(2)];
const docusaurus = spawn('npx', docusaurusArgs, { cwd: ROOT, stdio: 'inherit', shell: true });

docusaurus.on('close', (code) => {
  if (watcher && typeof watcher.close === 'function') watcher.close();
  process.exit(code || 0);
});
